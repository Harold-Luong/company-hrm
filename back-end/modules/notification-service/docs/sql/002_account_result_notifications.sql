CREATE TABLE IF NOT EXISTS account_result_notifications (
  event_id UUID PRIMARY KEY,
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  request_id UUID NOT NULL UNIQUE,
  employee_id UUID NOT NULL,
  recipient_user_id VARCHAR(255) NOT NULL,
  provisioning_status VARCHAR(20) NOT NULL CHECK (provisioning_status IN ('SUCCEEDED','FAILED')),
  error_code VARCHAR(50),
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS account_result_notifications_recipient_idx
  ON account_result_notifications(recipient_user_id, sequence);
