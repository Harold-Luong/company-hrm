CREATE TABLE IF NOT EXISTS notifications (
  event_id UUID PRIMARY KEY,
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  source VARCHAR(20) NOT NULL CHECK (source IN ('LEAVE','ATTENDANCE')),
  request_id UUID NOT NULL,
  request_version BIGINT NOT NULL,
  requester_user_id VARCHAR(255) NOT NULL,
  employee_id UUID NOT NULL,
  actor_user_id VARCHAR(255) NOT NULL,
  action VARCHAR(20) NOT NULL CHECK (action IN ('SUBMITTED','UPDATED','CANCELLED','APPROVED','REJECTED')),
  occurred_at TIMESTAMPTZ NOT NULL,
  UNIQUE(source, request_id, request_version)
);
CREATE INDEX IF NOT EXISTS notifications_owner_idx ON notifications(requester_user_id, sequence DESC);
CREATE TABLE IF NOT EXISTS notification_reads (
  event_id UUID NOT NULL REFERENCES notifications(event_id),
  user_id VARCHAR(255) NOT NULL,
  PRIMARY KEY(event_id, user_id)
);
