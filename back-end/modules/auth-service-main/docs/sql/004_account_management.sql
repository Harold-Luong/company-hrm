-- Run before deploying account administration. No account/session data is deleted.
BEGIN;
ALTER TABLE users ADD COLUMN IF NOT EXISTS administratively_locked BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS management_version BIGINT NOT NULL DEFAULT 0 CHECK (management_version >= 0);
CREATE TABLE IF NOT EXISTS account_management_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL,
    actor_email VARCHAR(255) NOT NULL,
    account_id BIGINT NOT NULL,
    account_email VARCHAR(255) NOT NULL,
    action VARCHAR(30) NOT NULL CHECK (action IN ('DISABLE', 'ENABLE', 'CHANGE_ROLES', 'REVOKE_SESSIONS')),
    reason VARCHAR(500) NOT NULL,
    before_status VARCHAR(30) NOT NULL,
    after_status VARCHAR(30) NOT NULL,
    before_roles VARCHAR(100) NOT NULL,
    after_roles VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
-- IDs and email snapshots are retained independently of account deletion.
CREATE INDEX IF NOT EXISTS account_management_audit_account_idx ON account_management_audit(account_id, id);

COMMIT;
